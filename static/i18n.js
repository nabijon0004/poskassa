let currentLanguage = DEFAULT_LANGUAGE;

function t(key, params = {}) {
  const text = TRANSLATIONS[currentLanguage][key] ?? TRANSLATIONS[DEFAULT_LANGUAGE][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? params[name] : match));
}

function hasTranslation(key) {
  return key in TRANSLATIONS[currentLanguage];
}

function setLanguage(language) {
  currentLanguage = LANGUAGES[language] ? language : DEFAULT_LANGUAGE;
  document.documentElement.lang = LANGUAGES[currentLanguage].htmlLang;
}

function numberLocale() {
  return LANGUAGES[currentLanguage].locale;
}
